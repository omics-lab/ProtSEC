#!/usr/bin/env python3
"""
k-NN Classifier for Enzyme Class Prediction using ProtSEC Distance Matrices

This script implements a k-NN classifier using the scikit-learn library in Python. 
The classifier is trained on protein sequence embeddings generated by the ProtSEC model, 
and it can be used to predict the enzyme class of new protein sequences based on their embeddings.

The input consists of pairwise distance matrices that are converted to similarity matrices 
by computing 1-Distance, and enzyme class annotations at multiple levels (EC1, EC2, EC3, EC All).
"""

